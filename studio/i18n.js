export function getLocale() {
  return locale;
}
export function tr(key, params = {}) {
  const value = messageTranslations[key]?.[{ fr: 0, en: 1, es: 2 }[locale]] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
export function translateError(error) {
  const message = String(error?.message ?? error ?? '');
  if (message.includes('At least two') || message.includes('Select at least two'))
    return tr('needScreens');
  if (message.includes('Selected screens must')) return tr('invalidSelection');
  if (message.includes('procedure title')) return tr('invalidTitle');
  if (message.includes('Step labels must')) return tr('invalidLabel');
  if (message.includes('macOS dans cette version')) return tr('ocrUnavailable');
  if (message.includes('Analyse de l’image précédente')) return tr('visualBusy');
  if (message.includes('Limite de 120 images')) return tr('visualLimit');
  if (message.includes('Capture non active')) return tr('visualSessionMissing');
  if (error?.name === 'NotAllowedError')
    return {
      fr: 'Partage d’écran refusé ou annulé.',
      en: 'Screen sharing was denied or canceled.',
      es: 'Se rechazó o canceló el uso compartido de pantalla.',
    }[locale];
  return message || tr('unknownError');
}
export function setLocale(next) {
  if (!['fr', 'en', 'es'].includes(next)) return;
  locale = next;
  try {
    localStorage.setItem('frontier.locale', next);
  } catch {}
  document.documentElement.lang = next;
  const selector = document.querySelector('#language-select');
  if (selector) selector.value = next;
  translateStatic();
  const title = document.querySelector('#visual-title');
  const defaults = staticTranslations.get('Ma procédure à l’écran');
  if (title && Object.values(defaults).includes(title.value)) title.value = defaults[next];
  document.dispatchEvent(new CustomEvent('frontier:localechange', { detail: { locale: next } }));
}
export function initI18n() {
  let saved;
  try {
    saved = localStorage.getItem('frontier.locale');
  } catch {}
  document
    .querySelector('#language-select')
    .addEventListener('change', (event) => setLocale(event.target.value));
  setLocale(['fr', 'en', 'es'].includes(saved) ? saved : 'fr');
}

