const staticTranslations = new Map(
  staticTranslationRows.map(([fr, en, es]) => [fr, { fr, en, es }]),
);
const originals = new WeakMap();
const attributeOriginals = new WeakMap();
let locale = 'fr';

function translateTextNode(node) {
  if (!originals.has(node)) originals.set(node, node.textContent);
  const original = originals.get(node);
  const key = original.replace(/\s+/g, ' ').trim();
  const translated = staticTranslations.get(key)?.[locale];
  if (!translated) return;
  node.textContent = original.match(/^\s*/)[0] + translated + original.match(/\s*$/)[0];
}

export function translateStatic(root = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!node.parentElement?.closest('script,style')) translateTextNode(node);
  }
  for (const element of root.querySelectorAll('[placeholder], [aria-label]')) {
    let saved = attributeOriginals.get(element);
    if (!saved) {
      saved = {
        placeholder: element.getAttribute('placeholder'),
        ariaLabel: element.getAttribute('aria-label'),
      };
      attributeOriginals.set(element, saved);
    }
    for (const [attribute, value] of [
      ['placeholder', saved.placeholder],
      ['aria-label', saved.ariaLabel],
    ]) {
      if (value && staticTranslations.has(value))
        element.setAttribute(
          attribute === 'aria-label' ? 'aria-label' : attribute,
          staticTranslations.get(value)[locale],
        );
    }
  }
}

